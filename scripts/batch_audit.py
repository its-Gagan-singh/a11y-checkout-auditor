"""Audit every URL in scripts/urls.txt and write docs/results.md.

Run from the project root (with the venv active):
    python -m scripts.batch_audit
"""
import os
import time
from pathlib import Path

from backend.app.crawler import audit_page
from backend.app.report import build_report

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    use_ml = os.getenv("USE_ML_ALT") == "1"
    urls = [
        line.strip()
        for line in (ROOT / "scripts" / "urls.txt").read_text().splitlines()
        if line.strip() and not line.startswith("#")
    ]
    rows, reports = [], []
    for url in urls:
        print("Auditing", url, flush=True)
        try:
            report = build_report(audit_page(url), use_ml=use_ml)
        except Exception as exc:
            print("  failed:", exc)
            rows.append(f"| {url} | failed | - | - | - | - |")
            continue
        s = report["summary"]
        reports.append(report)
        rows.append(
            f"| {url} | {report['score']} ({report['grade']}) | {s['total_issues']} | "
            f"{s['by_impact']['critical'] + s['by_impact']['serious']} | "
            f"{s['images_missing_alt']} | {s['auto_fix_pct']}% |"
        )
        time.sleep(1)

    total = sum(r["summary"]["total_issues"] for r in reports)
    suggested = sum(
        round(r["summary"]["total_issues"] * r["summary"]["auto_fix_pct"] / 100) for r in reports
    )
    lines = [
        "# Audit results",
        "",
        f"Pages audited successfully: **{len(reports)}** of {len(urls)}. "
        f"Total issues found: **{total}**. "
        f"Issues with a suggested fix: **{round(100 * suggested / total) if total else 100}%**.",
        "",
        "| Page | Score | Issues | Critical + serious | Images missing alt | Suggested fix |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        "Generated by `python -m scripts.batch_audit`.",
    ]
    (ROOT / "docs" / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Wrote docs/results.md")


if __name__ == "__main__":
    main()
